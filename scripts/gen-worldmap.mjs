// Regenerates the embedded dot-matrix world map + decoy relay nodes used by the
// GLOBAL TRACE panel and the feed OSD.
// Run: node scripts/gen-worldmap.mjs
// Output is embedded so the site stays self-contained (no runtime map dependency).
import DottedMap from "dotted-map";
import { writeFileSync } from "node:fs";

const HEIGHT = 36;

const map = new DottedMap({ height: HEIGHT, grid: "vertical" });
const pts = map.getPoints();
const cols = Math.round(Math.max(...pts.map((p) => p.x))) + 1;
const rows = Math.round(Math.max(...pts.map((p) => p.y))) + 1;

const grid = Array.from({ length: rows }, () => Array(cols).fill(" "));
for (const p of pts) {
  const c = Math.round(p.x);
  const r = Math.round(p.y);
  if (grid[r] && c < cols) grid[r][c] = "+";
}

const landNeighbours = (r, c) => {
  let n = 0;
  for (let dr = -1; dr <= 1; dr++) {
    for (let dc = -1; dc <= 1; dc++) {
      if ((dr || dc) && grid[r + dr]?.[c + dc] === "+") n++;
    }
  }
  return n;
};

// Project a lat/lng to a grid cell, snapping onto the nearest *mainland* dot (most
// land neighbours within a small radius) so a marker sits on the continent rather
// than on a lone island or in open water. Falls back to the nearest land dot.
const RADIUS = 4;
function snap(lat, lng) {
  const pin = map.addPin({ lat, lng });
  const target = { row: Math.round(pin.y), col: Math.round(pin.x) };
  let best = null;
  let bestScore = -Infinity;
  let fallback = null;
  let fbDist = Infinity;
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (grid[r][c] !== "+") continue;
      const d = (r - target.row) ** 2 + (c - target.col) ** 2;
      if (d < fbDist) {
        fbDist = d;
        fallback = { row: r, col: c };
      }
      if (d <= RADIUS * RADIUS) {
        const score = landNeighbours(r, c) - d / 100;
        if (score > bestScore) {
          bestScore = score;
          best = { row: r, col: c };
        }
      }
    }
  }
  return best || fallback || target;
}

// --- world map ---
const lines = grid.map((row) => row.join("").padEnd(cols, " "));
const body = lines.map((l) => "  " + JSON.stringify(l) + ",").join("\n");
writeFileSync(
  "src/lib/worldMap.ts",
  `// Dot-matrix world map (land cells as "+"), generated by scripts/gen-worldmap.mjs.
// Edit that script and regenerate rather than hand-editing this file.
export const WORLD_MAP_COLS = ${cols};
export const WORLD_MAP_ROWS: string[] = [
${body}
];
`,
);
console.log(`wrote src/lib/worldMap.ts (${cols}x${rows})`);

// --- decoy relay nodes (proxychains origins) ---
function toDMS(value, pos, neg) {
  const dir = value >= 0 ? pos : neg;
  const abs = Math.abs(value);
  const deg = Math.floor(abs);
  const minFloat = (abs - deg) * 60;
  const min = Math.floor(minFloat);
  const sec = Math.round((minFloat - min) * 60);
  return `${deg}°${String(min).padStart(2, "0")}'${String(sec).padStart(2, "0")}"${dir}`;
}

const RELAY_CITIES = [
  { city: "REYKJAVIK", region: "REYKJAVIK, IS", lat: 64.1466, lng: -21.9426 },
  { city: "MONTREAL", region: "MONTREAL, CA", lat: 45.5019, lng: -73.5674 },
  { city: "SAO PAULO", region: "SAO PAULO, BR", lat: -23.5558, lng: -46.6396 },
  { city: "LAGOS", region: "LAGOS, NG", lat: 6.5244, lng: 3.3792 },
  { city: "ZURICH", region: "ZURICH, CH", lat: 47.3769, lng: 8.5417 },
  { city: "TOKYO", region: "TOKYO, JP", lat: 35.6762, lng: 139.6503 },
  { city: "SINGAPORE", region: "SINGAPORE, SG", lat: 1.3521, lng: 103.8198 },
  { city: "SYDNEY", region: "SYDNEY, AU", lat: -33.8688, lng: 151.2093 },
];

const relays = RELAY_CITIES.map((c) => ({
  city: c.city,
  region: c.region,
  decimal: `${c.lat.toFixed(6)}, ${c.lng.toFixed(6)}`,
  dms: `${toDMS(c.lat, "N", "S")} ${toDMS(c.lng, "E", "W")}`,
  cell: snap(c.lat, c.lng),
}));

writeFileSync(
  "src/lib/relays.ts",
  `// Decoy relay nodes (proxychains origins), generated by scripts/gen-worldmap.mjs.
// Edit that script and regenerate rather than hand-editing this file.
export type Relay = {
  city: string;
  region: string;
  decimal: string;
  dms: string;
  cell: { row: number; col: number };
};
export const RELAYS: Relay[] = ${JSON.stringify(relays, null, 2)};
`,
);
console.log(`wrote src/lib/relays.ts (${relays.length} nodes)`);
