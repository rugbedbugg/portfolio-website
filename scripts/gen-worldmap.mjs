// Regenerates the embedded dot-matrix world map used by the GLOBAL TRACE panel.
// Run: node scripts/gen-worldmap.mjs
// Output is embedded so the site stays self-contained (no runtime map dependency).
import DottedMap from "dotted-map";
import { writeFileSync } from "node:fs";

const HEIGHT = 36;
const MARKER_LAT = 12.9165; // Vellore, TN, IN
const MARKER_LNG = 79.1325;

const map = new DottedMap({ height: HEIGHT, grid: "vertical" });
const pts = map.getPoints();
const cols = Math.round(Math.max(...pts.map((p) => p.x))) + 1;
const rows = Math.round(Math.max(...pts.map((p) => p.y))) + 1;

const grid = Array.from({ length: rows }, () => Array(cols).fill(" "));
for (const p of pts) {
  const c = Math.round(p.x);
  const r = Math.round(p.y);
  if (grid[r] && c < cols) grid[r][c] = "+";
}

const pin = map.addPin({ lat: MARKER_LAT, lng: MARKER_LNG });
const target = { row: Math.round(pin.y), col: Math.round(pin.x) };

// Snap the projected pin onto the nearest *mainland* cell (a land dot with
// several land neighbours) so the marker sits on the continent rather than on a
// lone island or in open water. Fall back to the nearest land dot of any kind.
const landNeighbours = (r, c) => {
  let n = 0;
  for (let dr = -1; dr <= 1; dr++) {
    for (let dc = -1; dc <= 1; dc++) {
      if ((dr || dc) && grid[r + dr]?.[c + dc] === "+") n++;
    }
  }
  return n;
};
const RADIUS = 4;
let best = null;
let bestScore = -Infinity;
let fallback = null;
let fbDist = Infinity;
for (let r = 0; r < rows; r++) {
  for (let c = 0; c < cols; c++) {
    if (grid[r][c] !== "+") continue;
    const d = (r - target.row) ** 2 + (c - target.col) ** 2;
    if (d < fbDist) {
      fbDist = d;
      fallback = { row: r, col: c };
    }
    // Within a small radius of the projected pin, prefer the densest land
    // (most land neighbours), tie-broken by proximity, so the marker settles
    // into the mainland rather than a sparse coastal or island dot.
    if (d <= RADIUS * RADIUS) {
      const score = landNeighbours(r, c) - d / 100;
      if (score > bestScore) {
        bestScore = score;
        best = { row: r, col: c };
      }
    }
  }
}
const marker = best || fallback || target;

const lines = grid.map((row) => row.join("").padEnd(cols, " "));
const body = lines.map((l) => "  " + JSON.stringify(l) + ",").join("\n");

const out = `// Dot-matrix world map (land cells as "+"), generated by scripts/gen-worldmap.mjs.
// Edit that script and regenerate rather than hand-editing this file.
export const WORLD_MAP_COLS = ${cols};
export const WORLD_MAP_MARKER = { row: ${marker.row}, col: ${marker.col} };
export const WORLD_MAP_ROWS: string[] = [
${body}
];
`;

writeFileSync("src/lib/worldMap.ts", out);
console.log(`wrote src/lib/worldMap.ts (${cols}x${rows}, marker r${marker.row} c${marker.col})`);
